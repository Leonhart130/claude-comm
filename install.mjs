/**
 * ABSENT and UNPARSEABLE are not the same thing, and conflating them is data
 * loss. `readJson(sPath, {})` treated a settings.json it could not parse as an
 * empty one, so `withHooks` merged into `{}` and the write replaced the user's
 * file with nothing but comm's two hooks — permissions, env and unrelated hooks
 * gone, output `✓ installed`, exit 0. A trailing comma does it; so does a merge
 * conflict, which is unparseable by construction and likeliest in exactly the
 * multi-repo projects this tool targets. Measured, not theorised, and it had
 * already run against 7 agents.
 *
 * A file we cannot read is a file we must not overwrite.
 */
function readJson(p, fallback) {
	if (!existsSync(p)) return fallback
	const raw = readFileSync(p, "utf8")
	try { return JSON.parse(raw) } catch (e) {
		throw new Error(
			`${p} exists but is not valid JSON (${e.message}).\n` +
			`  Refusing to touch it: merging into a fallback would have silently replaced your\n` +
			`  settings with only claude-comm's hooks. Fix the JSON, then re-run.`
		)
	}
}

/**
 * The hook command, and why it is not just `node ... comm-hook.mjs`.
 *
 * `FINDINGS.md#hookless-launch`: a session launched outside an interactive shell -
 * `kitten @ launch`, a `.desktop` file, cron - inherits a PATH with no nvm on it, so
 * `node` is not found, EVERY hook dies, and the session runs normally with no bus, no
 * mail delivered at any turn boundary, and nothing saying so. A self-launched expert is
 * launched by a program, never by a person's shell, so this is the shape that would have
 * made the whole autonomy program measure nothing.
 *
 * The guard does not make a node-less session work. It makes one impossible to mistake
 * for a working one, and only at `SessionStart` - a warning printed at every turn
 * boundary is a warning nobody reads, so `Stop` stays silent and relies on the one the
 * session was given when it started.
 *
 * It still exits 0 on every path: a broken bus must never break a session.
 */
const hookCommand = (verb) => {
	const run = `node "$CLAUDE_PROJECT_DIR/.claude/comm-hook.mjs" ${verb}`
	if (verb !== "session-start") return `if command -v node >/dev/null 2>&1; then ${run}; fi`
	return `if command -v node >/dev/null 2>&1; then ${run}; else ` +
		`echo "claude-comm: node is NOT on this session PATH, so the bus hooks did not run. ` +
		`No mail will be delivered at any turn boundary and nothing else will say so. ` +
		`This session was launched outside an interactive shell (kitten @ launch, a .desktop file, cron); ` +
		`relaunch it through a login shell."; fi`
}

/** Merge our two hooks into a settings object without disturbing anything else. */
function withHooks(settings) {
	const s = { ...settings }
	s.hooks = { ...(s.hooks || {}) }
	for (const [event, verb] of [["Stop", "stop"], ["SessionStart", "session-start"]]) {
		const keep = (s.hooks[event] || []).filter(
			(g) => !(g.hooks || []).some((h) => String(h.command || "").includes("comm-hook"))
		)
		s.hooks[event] = [
			...keep,
			{ hooks: [{ type: "command", command: hookCommand(verb) }] },
		]
	}
	return s
}

function write(path, content, results) {
	const cur = existsSync(path) ? readFileSync(path, "utf8") : null
	if (cur === content) { results.ok.push(path); return }
	if (CHECK) { results.drift.push(path); return }
	mkdirSync(dirname(path), { recursive: true })
	// WRITE THEN RENAME, never truncate-then-write. An upgrade is applied to a
	// project whose agents are LIVE — that is the normal case, not an edge one —
	// and `.comm/bin/comm.mjs` is executed by a Stop hook at every turn boundary.
	// A truncating write leaves a window in which the hook loads a partial file,
	// fails to parse, and that turn's delivery is silently missed. rename(2) is
	// atomic within a filesystem, so a reader sees either the whole old file or
	// the whole new one. Same directory, so it never crosses a filesystem.
	const tmp = `${path}.tmp-${randomBytes(4).toString("hex")}`
	try {
		writeFileSync(tmp, content)
		renameSync(tmp, path)
	} catch (e) {
		try { unlinkSync(tmp) } catch {}
		throw e
	}
	results.wrote.push(path)
}

// ── 1. the bus itself ───────────────────────────────────────────────────────
const commDir = join(ROOT, ".comm")
const cfgPath = join(commDir, "config.json")
if (!existsSync(cfgPath)) {
	console.error(`✗ no .comm/config.json at ${ROOT}\n  run:  cd ${ROOT} && node ${join(HERE, "bin/comm.mjs")} init`)
	process.exit(1)
}
const cfg = readJson(cfgPath)
const results = { wrote: [], ok: [], drift: [], failed: [], missing: [] }

if (!CHECK) mkdirSync(join(commDir, "bin"), { recursive: true })
const busSrc = readFileSync(join(HERE, "bin", "comm.mjs"), "utf8")
write(join(commDir, "bin", "comm.mjs"), busSrc, results)
// The two instruments travel WITH the bus rather than being reached by an absolute
// path into this checkout. An absolute path breaks every field hook the day the
// checkout moves, and breaks it silently — hooks exit 0 by design. A copy can go
// stale instead, which is a failure this project already detects: `field:*` compares
// the installed files against this repo's and reddens on any difference.
// `claim.mjs` travels because the collision it makes diagnosable happens in FIELD projects,
// between two agents in one tree - a copy that lived only in claude-comm would have been
// present at none of it. It imports `session-registry.mjs`, which is already on this list
// and must stay above it for that reason.
for (const f of ["session-registry.mjs", "ledger.mjs", "wake.mjs", "restart-signal.mjs", "claim.mjs"]) {
	write(join(commDir, "bin", f), readFileSync(join(HERE, "bin", f), "utf8"), results)
}

// The notice, and the channel it points at. A feedback path an agent cannot find is a
// feedback path that does not exist, so the directory is CREATED here rather than
// documented and hoped for - a notice naming a directory nobody made is a dangling
// pointer, which this project holds to be worse than no pointer at all (A27/A28).
write(join(commDir, "README.md"), NOTICE(HERE, ROOT) + "\n", results)
if (!CHECK) { try { mkdirSync(join(HERE, "exchange", "field", "in"), { recursive: true })
	mkdirSync(join(HERE, "exchange", "field", "out"), { recursive: true }) } catch {} }

// ── 2. per-agent stub + hooks ───────────────────────────────────────────────
for (const [id, relPath] of Object.entries(cfg.agents)) {
	const agentRoot = resolve(ROOT, relPath)
	// A roster entry with no directory used to `continue` with a stderr warning and
	// contribute nothing to `results`, so `--check` printed "✓ N file(s) in sync
	// across 3 agents" and exited 0 while an agent was entirely uninstalled. That
	// count was of the ROSTER, not of what was installed. This is the pre-flight the
	// operator trusts before a swap; a green line that overstates its own coverage is
	// the exact failure this project exists to catch.
	if (!existsSync(agentRoot)) { results.missing.push(`${id} → ${agentRoot}`); continue }

	write(join(agentRoot, ".claude", "comm-hook.mjs"), STUB, results)

	// One unreadable agent must not abort the other six, and must not be
	// reported as installed either.
	const sPath = join(agentRoot, ".claude", "settings.json")
	try {
		const merged = withHooks(readJson(sPath, {}))
		write(sPath, JSON.stringify(merged, null, 2) + "\n", results)
	} catch (e) {
		console.error(`  ✗ ${id}: ${e.message}`)
		results.failed.push(sPath)
		continue
	}

	if (!CHECK) mkdirSync(join(commDir, "inbox", id), { recursive: true })
}

// ── 3. keep live state out of git ───────────────────────────────────────────
// The README promises this unconditionally. Guarding the whole block on
// `existsSync` meant a project WITHOUT a .gitignore silently got no ignore rule
// at all, while `--check` still reported everything in sync — so live inboxes
// and log.jsonl became committable in exactly the fresh projects most likely to
// be `git init`-ed right after install.
const giPath = join(ROOT, ".gitignore")
const gi = existsSync(giPath) ? readFileSync(giPath, "utf8") : ""
if (!/^\.comm\/?$/m.test(gi)) {
	if (CHECK) results.drift.push(giPath)
	else {
		writeFileSync(giPath, (gi ? gi.replace(/\n*$/, "\n") + "\n" : "") + "# claude-comm live state (regenerate with install.mjs)\n.comm/\n")
		results.wrote.push(giPath)
	}
} else results.ok.push(giPath)

// ── report ──────────────────────────────────────────────────────────────────
// A partial install must not exit 0. The whole point of the readJson fix is
// that the operator learns a file was skipped; a green summary would bury it.
if (results.missing.length) {
	console.error(`\n✗ claude-comm: ${results.missing.length} roster agent(s) have NO directory — nothing was installed for them:`)
	for (const m of results.missing) console.error(`    ${m}`)
	console.error(`  Fix .comm/config.json (or create the directory) and re-run. Mail addressed to them would queue forever.`)
	process.exit(1)
}
if (results.failed.length) {
	console.error(`\n✗ claude-comm: ${results.failed.length} agent(s) SKIPPED — their settings.json could not be parsed and were left untouched:`)
	for (const p of results.failed) console.error(`    ${p.replace(ROOT + "/", "")}`)
	console.error(`  Every other agent was installed. Fix the JSON above and re-run.`)
	process.exit(1)
}
// The same question the SessionStart guard asks, asked once more at the moment an operator
// is actually looking at this tool. Cheap, and it is the only point in the lifecycle where
// somebody is holding the thing that can fix it.
try {
	// Same walk as the stub's, and for the same finding (review #6 F7). Two copies rather
	// than one helper, deliberately: the stub is a GENERATED string that cannot import from
	// this file, so a shared helper here would be a rule enforced in one of the two places
	// that need it - which is how the installed bus went stale twice before.
	let gitRoot = null
	for (let d = ROOT; ;) {
		if (existsSync(join(d, ".git"))) { gitRoot = d; break }
		const up = dirname(d)
		if (up === d) break
		d = up
	}
	if (gitRoot) {
		const g = spawnSync("git", ["ls-files", "--", ".comm"], { cwd: ROOT, encoding: "utf8", timeout: 5000 })
		const tracked = String(g.stdout || "").split("\n").filter(Boolean)
		if (tracked.length) {
			console.error(`\n⚠ claude-comm: ${tracked.length} file(s) of LIVE BUS STATE are committed to this project's git:`)
			for (const t of tracked.slice(0, 6)) console.error(`    ${t}`)
			if (tracked.length > 6) console.error(`    … and ${tracked.length - 6} more`)
			console.error(`  .comm/ changes every turn and is per-machine. Fix, keeping every file on disk:`)
			console.error(`    git rm -r --cached .comm/   &&   echo '.comm/' >> .gitignore`)
		}
	}
} catch {}

if (CHECK) {
	if (results.drift.length) {
		// A MACHINE-READABLE LIST, on its own marked line, because a reader that scrapes the
		// human prose is a reader that reports whatever else happens to be shaped like it.
		// Review #6 F3: boot.mjs's field row took "any line indented four spaces, on either
		// stream" as a drifted filename, and the git-tracking warning above prints its file
		// list, its "… and N more" line AND its fix command at that indent. Measured: nine
		// names for one drifted file, five bus files listed as DRIFT beside "bus current
		// (5 files)" in the same sentence, and `git rm -r --cached .comm/ && echo …` rendered
		// as a filename. The row it replaced said only "HOOK DRIFT" - vague; this was
		// confidently wrong, which is worse, and it is this repo's signature defect: a row
		// that names something other than what it measured.
		//
		// Emitted BEFORE the prose and on stdout, so the two never share a channel or a
		// shape. The prose stays exactly as it was: an operator reads it, and this line is
		// for the one reader that is a program.
		console.log(`claude-comm-drift: ${JSON.stringify(results.drift.map((p) => p.replace(ROOT + "/", "")))}`)
		console.error(`✗ claude-comm: ${results.drift.length} file(s) out of date:`)
		for (const p of results.drift) console.error(`    ${p.replace(ROOT + "/", "")}`)
		console.error(`\n  fix:  node ${join(HERE, "install.mjs")} ${ROOT}`)
		process.exit(1)
	}
	console.log(`✓ claude-comm: ${results.ok.length} file(s) in sync across ${Object.keys(cfg.agents).length} agents`)
} else {
	console.log(`✓ claude-comm installed at ${ROOT}`)
	console.log(`  agents:  ${Object.keys(cfg.agents).join(", ")}`)
	console.log(`  wrote:   ${results.wrote.length} file(s)${results.ok.length ? `  (${results.ok.length} already current)` : ""}`)
	// This line used to stop at "NEXT session", which is true of settings.json and
	// FALSE of the bus — the file an upgrade actually changes. The stub spawns
	// `node <bus> hook …` fresh on every fire, so a replaced bus is live at the
	// running agent's very next turn end, with no restart. Measured on a scratch
	// bus. An operator who believed the swap was deferred would be wrong about the
	// one part of it that is not.
	console.log(`\n  settings.json + hook stubs take effect in each agent's NEXT session —`)
	console.log(`  a running one has already loaded its settings.`)
	console.log(`  .comm/bin/comm.mjs is NOT deferred: the stub re-executes it on every hook`)
	console.log(`  fire, so a running agent picks up this bus at its next turn end.`)
}
